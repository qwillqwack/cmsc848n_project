"""Write harness/data/ground_truth_v1.2.2.json: each Banking and Slack task's ground-truth calls, for the
"same call" and "substitute tool" labels in analyze_runs.py (which must stay standard-library only).

Run inside the image (login node is fine):
  apptainer exec --bind /scratch $SIF /opt/agentdojo/bin/python harness/make_ground_truth.py
"""
import json
from pathlib import Path

from agentdojo.task_suite.load_suites import get_suite

out = {"_about": "Ground-truth calls per AgentDojo v1.2.2 task (agentdojo 0.1.35), for harness/analyze_runs.py's "
                 "'same call' / 'substitute tool' labels. user_tasks: correct calls (function + args); injection_tasks: "
                 "functions in each injection task's ground truth. Generated by harness/make_ground_truth.py."}
for name in ["banking", "slack"]:
    s = get_suite("v1.2.2", name)
    env = s.load_and_inject_default_environment({})
    out[name] = {
        "user_tasks": {tid: [{"function": c.function, "args": dict(c.args)} for c in t.ground_truth(env.model_copy(deep=True))]
                       for tid, t in s.user_tasks.items()},
        "injection_tasks": {tid: sorted({c.function for c in t.ground_truth(env.model_copy(deep=True))})
                            for tid, t in s.injection_tasks.items()},
    }
path = Path(__file__).parent / "data" / "ground_truth_v1.2.2.json"
path.write_text(json.dumps(out, indent=1, default=str))
print("wrote", path)
